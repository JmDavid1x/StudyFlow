/// Radios de borde. Cada uno tiene un uso, para que no todo sea una píldora.
abstract final class SfRadius {
  /// Insignias y segmentos pequeños.
  static const double sm = 8;

  /// Campos de texto, filas y selectores.
  static const double md = 12;

  /// Tarjetas y botones grandes.
  static const double lg = 16;

  /// Hojas inferiores (bottom sheets).
  static const double sheet = 28;

  /// Chips de filtro: el único elemento en forma de píldora.
  static const double pill = 999;
}
